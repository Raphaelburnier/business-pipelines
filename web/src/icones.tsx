// Les icônes du cockpit : Lucide, trait 1,75, héritent de `currentColor`. Une icône seule
// porte toujours un libellé sur son bouton. Les vues ne connaissent que ces noms : changer
// de dessin ne touche qu'ici.
import {
  Activity,
  Bot,
  Calendar,
  Camera,
  ChartLine,
  Check,
  ChevronDown,
  ChevronsUpDown,
  ChevronUp,
  CircleAlert,
  CircleCheck,
  CirclePlay,
  CircleX,
  Clock,
  ExternalLink,
  Flag,
  GitBranch,
  Inbox,
  Info,
  LayoutDashboard,
  ListChecks,
  LoaderCircle,
  Megaphone,
  Menu,
  MessageSquare,
  Moon,
  Network,
  Pause,
  RotateCw,
  Server,
  ShieldAlert,
  Sun,
  TriangleAlert,
  WifiOff,
  Workflow,
  X,
  type LucideIcon,
} from "lucide-react";

const ICONES = {
  menu: Menu,
  fermer: X,
  accueil: LayoutDashboard,
  graphe: Network,
  agent: Bot,
  mission: Flag,
  pipeline: Workflow,
  run: CirclePlay,
  marketing: Megaphone,
  demander: MessageSquare,
  finance: ChartLine,
  studio: Camera,
  systeme: Server,
  avenir: ListChecks,
  calendrier: Calendar,
  branche: GitBranch,
  decision: CircleCheck,
  soleil: Sun,
  lune: Moon,
  ouvrir: ExternalLink,
  activite: Activity,
  alerte: CircleAlert,
  attention: TriangleAlert,
  info: Info,
  ok: Check,
  echec: CircleX,
  horloge: Clock,
  pause: Pause,
  sensible: ShieldAlert,
  horsLigne: WifiOff,
  vide: Inbox,
  reessayer: RotateCw,
  chargement: LoaderCircle,
  tri: ChevronsUpDown,
  triMonte: ChevronUp,
  triDescend: ChevronDown,
} satisfies Record<string, LucideIcon>;

export type NomIcone = keyof typeof ICONES;

export function Icone({ nom, taille = 20, className = "" }: { nom: NomIcone; taille?: number; className?: string }) {
  const Dessin = ICONES[nom];
  return <Dessin size={taille} strokeWidth={1.75} aria-hidden="true" focusable="false" className={`flex-none ${className}`} />;
}
